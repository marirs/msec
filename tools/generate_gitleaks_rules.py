#!/usr/bin/env python3
"""Generates src/secrets/generated/gitleaks.rs from gitleaks' default rule set.

Usage: generate_gitleaks_rules.py <gitleaks.toml> <tag>

<gitleaks.toml> is config/gitleaks.toml of the gitleaks release <tag>
(https://github.com/gitleaks/gitleaks, MIT License). The output records the tag and the
file's SHA-256 so a regeneration can be checked against the same input.

Rules are emitted as data only; how each rule's finding is classified (credential, client key,
possible secret) is decided in src/secrets/rules.rs, by hand, so a gitleaks update cannot
silently change a severity.
"""

import hashlib
import re
import sys
import tomllib
from pathlib import Path

OUTPUT = Path(__file__).resolve().parent.parent / "src/secrets/generated/gitleaks.rs"


def raw(text: str) -> str:
    """A Rust raw string literal that can hold `text`."""
    hashes = 1
    while '"' + "#" * hashes in text:
        hashes += 1
    fence = "#" * hashes
    return f'r{fence}"{text}"{fence}'


def strings(values) -> str:
    return "&[" + ", ".join(raw(value) for value in values) + "]"


REPETITION = re.compile(r"\{\d+(?:,\d*)?\}")


def rust_pattern(pattern: str) -> str:
    """RE2 reads a `{` that does not start a valid repetition as a literal; the `regex` crate
    rejects it. Escape those braces outside character classes; nothing else differs."""
    out = []
    position = 0
    in_class = False
    while position < len(pattern):
        character = pattern[position]
        if character == "\\":
            out.append(pattern[position:position + 2])
            position += 2
            continue
        if in_class:
            if character == "]":
                in_class = False
        elif character == "[":
            in_class = True
            # A `]` right after `[` or `[^` is a literal member, not the end.
            out.append(character)
            position += 1
            if pattern[position:position + 1] == "^":
                out.append("^")
                position += 1
            if pattern[position:position + 1] == "]":
                out.append("]")
                position += 1
            continue
        elif character == "{" and not REPETITION.match(pattern, position):
            out.append("\\{")
            position += 1
            continue
        out.append(character)
        position += 1
    return "".join(out)


def allowlist(entry: dict) -> str:
    target = {"secret": "Secret", "match": "Match", "line": "Line"}[entry.get("regexTarget", "secret")]
    condition = {"OR": "Any", "AND": "All"}[entry.get("condition", "OR").upper()]
    unknown = set(entry) - {"description", "regexTarget", "condition", "regexes", "stopwords", "paths"}
    if unknown:
        raise SystemExit(f"unsupported allowlist keys: {sorted(unknown)}")
    return (
        "Allowlist { "
        f"condition: Condition::{condition}, "
        f"target: Target::{target}, "
        f"regexes: {strings(rust_pattern(value) for value in entry.get('regexes', []))}, "
        f"stopwords: {strings(entry.get('stopwords', []))}, "
        f"paths: {strings(rust_pattern(value) for value in entry.get('paths', []))} "
        "}"
    )


def rule(entry: dict) -> str:
    unknown = set(entry) - {"id", "description", "regex", "secretGroup", "entropy", "keywords", "path", "allowlists"}
    if unknown:
        raise SystemExit(f"{entry['id']}: unsupported keys {sorted(unknown)}")
    entropy = entry.get("entropy")
    return (
        "    GitleaksRule {\n"
        f"        id: {raw(entry['id'])},\n"
        f"        description: {raw(entry['description'])},\n"
        f"        regex: {('Some(' + raw(rust_pattern(entry['regex'])) + ')') if 'regex' in entry else 'None'},\n"
        f"        path: {('Some(' + raw(rust_pattern(entry['path'])) + ')') if 'path' in entry else 'None'},\n"
        f"        secret_group: {entry.get('secretGroup', 0)},\n"
        f"        entropy: {('Some(' + repr(float(entropy)) + ')') if entropy is not None else 'None'},\n"
        f"        keywords: {strings(entry.get('keywords', []))},\n"
        f"        allowlists: &[{', '.join(allowlist(item) for item in entry.get('allowlists', []))}],\n"
        "    },\n"
    )


def main() -> None:
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    source = Path(sys.argv[1])
    tag = sys.argv[2]
    data = source.read_bytes()
    config = tomllib.loads(data.decode("utf-8"))
    digest = hashlib.sha256(data).hexdigest()
    rules = config["rules"]
    output = [
        "// Generated by tools/generate_gitleaks_rules.py; do not edit.\n",
        f"// Source: gitleaks {tag}, config/gitleaks.toml (SHA-256 {digest}).\n",
        "// gitleaks is Copyright (c) 2019 Zachary Rice, MIT License (see GITLEAKS-LICENSE).\n\n",
        "use crate::secrets::rules::{Allowlist, Condition, GitleaksRule, Target};\n\n",
        f"/// The gitleaks release the rules come from.\npub(crate) const VERSION: &str = {raw(tag)};\n\n",
        "/// gitleaks' global allowlist: values and paths no rule reports.\n",
        f"pub(crate) static GLOBAL_ALLOWLIST: Allowlist = {allowlist(config['allowlist'])};\n\n",
        f"/// The {len(rules)} rules, in gitleaks' order.\n",
        "pub(crate) static RULES: &[GitleaksRule] = &[\n",
    ]
    output.extend(rule(entry) for entry in rules)
    output.append("];\n")
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("".join(output))
    print(f"{len(rules)} rules from gitleaks {tag} written to {OUTPUT}")


if __name__ == "__main__":
    main()
