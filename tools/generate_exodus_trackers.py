#!/usr/bin/env python3
"""Generates src/trackers/generated/exodus.rs from a snapshot of the εxodus tracker database.

Usage: generate_exodus_trackers.py <trackers.json> <retrieved yyyy-mm-dd>

<trackers.json> is the response of https://reports.exodus-privacy.eu.org/api/trackers (the file
MobSF keeps as signatures/exodus_trackers and refreshes from the same address). The εxodus
database and API results are made available under the Open Database License 1.0, and its
contents under the Database Contents License 1.0; the generated file is a derivative database
and carries that notice and the snapshot's SHA-256.

Every field is kept as Exodus publishes it; trackers are ordered by their numeric ID.
"""

import hashlib
import json
import sys
from pathlib import Path

OUTPUT = Path(__file__).resolve().parent.parent / "src/trackers/generated/exodus.rs"


def raw(text: str) -> str:
    """A Rust raw string literal that can hold `text`."""
    hashes = 1
    while '"' + "#" * hashes in text:
        hashes += 1
    fence = "#" * hashes
    return f'r{fence}"{text}"{fence}'


def main() -> None:
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    source = Path(sys.argv[1])
    retrieved = sys.argv[2]
    data = source.read_bytes()
    trackers = json.loads(data.decode("utf-8"))["trackers"]
    digest = hashlib.sha256(data).hexdigest()
    lines = [
        "// Generated by tools/generate_exodus_trackers.py; do not edit.\n",
        f"// Source: https://reports.exodus-privacy.eu.org/api/trackers, retrieved {retrieved}\n",
        f"// (SHA-256 {digest}).\n",
        "// This file is a derivative of the εxodus tracker database, Copyright Exodus Privacy,\n",
        "// made available under the Open Database License 1.0\n",
        "// (https://opendatacommons.org/licenses/odbl/1.0/); its contents are under the Database\n",
        "// Contents License 1.0 (https://opendatacommons.org/licenses/dbcl/1.0/). This file is\n",
        "// offered under the Open Database License 1.0.\n\n",
        "use crate::trackers::ExodusTracker;\n\n",
        f"/// When the snapshot was retrieved.\npub(crate) const RETRIEVED: &str = {raw(retrieved)};\n\n",
        f"/// The {len(trackers)} trackers, by ID.\n",
        "pub(crate) static TRACKERS: &[ExodusTracker] = &[\n",
    ]
    for key in sorted(trackers, key=int):
        tracker = trackers[key]
        categories = ", ".join(raw(category) for category in tracker["categories"])
        lines.append(
            "    ExodusTracker {\n"
            f"        id: {int(tracker['id'])},\n"
            f"        name: {raw(tracker['name'])},\n"
            f"        website: {raw(tracker['website'])},\n"
            f"        categories: &[{categories}],\n"
            f"        code_signature: {raw(tracker['code_signature'])},\n"
            f"        network_signature: {raw(tracker['network_signature'])},\n"
            f"        creation_date: {raw(tracker['creation_date'])},\n"
            "    },\n"
        )
    lines.append("];\n")
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("".join(lines))
    print(f"{len(trackers)} trackers written to {OUTPUT}")


if __name__ == "__main__":
    main()
