#!/usr/bin/env python3
"""Generate msec's Android framework data tables.

Inputs (all Apache-2.0, from the Android Open Source Project):

  --public-xml        Android SDK  platforms/android-<N>/data/res/values/public-final.xml
                      (framework attribute names and resource IDs)
  --framework-manifest AOSP        frameworks/base/core/res/AndroidManifest.xml
                      (framework permissions and their protection levels)
  --framework-strings  AOSP        frameworks/base/core/res/res/values/strings.xml
                      (permission labels shown to users)

Outputs:

  src/android/generated/attributes.rs
  src/android/generated/permissions.rs

Run from the repository root, for example:

  python3 tools/generate_android_data.py \
      --public-xml ~/Library/Android/sdk/platforms/android-37.0/data/res/values/public-final.xml \
      --framework-manifest AndroidManifest.xml --framework-strings strings.xml \
      --manifest-source "android16-qpr2-release" --sdk-source "Android SDK Platform 37"

The AOSP files are fetched from android.googlesource.com, for example
https://android.googlesource.com/platform/frameworks/base/+/refs/heads/android16-qpr2-release/core/res/AndroidManifest.xml?format=TEXT
(base64-encoded).
"""

from __future__ import annotations

import argparse
import re
import xml.etree.ElementTree as ElementTree
from pathlib import Path

ANDROID = "{http://schemas.android.com/apk/res/android}"


def rust_string(text: str) -> str:
    text = re.sub(r"\s+", " ", text).strip()
    escaped = text.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def framework_attributes(public_xml: Path) -> list[tuple[int, str]]:
    """Attribute IDs come either explicitly (`id=`) or from a group's `first-id` plus position."""
    root = ElementTree.parse(public_xml).getroot()
    found: dict[int, str] = {}
    for element in root:
        if element.tag == "public" and element.get("type") == "attr" and element.get("id"):
            found[int(element.get("id"), 16)] = element.get("name")
        elif element.tag == "public-group" and element.get("type") == "attr":
            next_id = int(element.get("first-id"), 16)
            for child in element:
                if child.tag != "public":
                    continue
                if child.get("id"):
                    next_id = int(child.get("id"), 16)
                found[next_id] = child.get("name")
                next_id += 1
    return sorted(found.items())


def unescape_android_string(text: str) -> str:
    text = text.strip()
    if len(text) >= 2 and text[0] == '"' and text[-1] == '"':
        text = text[1:-1]
    return re.sub(r"\\(.)", lambda match: {"n": " ", "t": " "}.get(match.group(1), match.group(1)), text)


def framework_strings(strings_xml: Path) -> dict[str, str]:
    root = ElementTree.parse(strings_xml).getroot()
    return {
        element.get("name"): unescape_android_string("".join(element.itertext()))
        for element in root.iter("string")
        if element.get("name")
    }


def framework_permissions(manifest: Path, strings: dict[str, str]) -> list[tuple[str, str, str | None]]:
    root = ElementTree.parse(manifest).getroot()
    permissions: dict[str, tuple[str, str | None]] = {}
    for element in root.iter("permission"):
        name = element.get(ANDROID + "name")
        if not name:
            continue
        level = element.get(ANDROID + "protectionLevel") or "normal"
        label_reference = element.get(ANDROID + "label") or ""
        label = strings.get(label_reference.removeprefix("@string/")) if label_reference.startswith("@string/") else None
        permissions[name] = (level, label)
    return sorted((name, level, label) for name, (level, label) in permissions.items())


HEADER = "// Generated by tools/generate_android_data.py from {source}. Do not edit by hand.\n\n"


def write_attributes(path: Path, attributes: list[tuple[int, str]], source: str) -> None:
    lines = [HEADER.format(source=source)]
    lines.append("/// Framework attribute resource IDs (`android:` attributes) and their names, sorted by ID.\n")
    lines.append("pub(crate) const FRAMEWORK_ATTRIBUTES: &[(u32, &str)] = &[\n")
    for resource_id, name in attributes:
        lines.append(f"    (0x{resource_id:08x}, {rust_string(name)}),\n")
    lines.append("];\n")
    path.write_text("".join(lines))


def write_permissions(path: Path, permissions: list[tuple[str, str, str | None]], source: str) -> None:
    lines = [HEADER.format(source=source)]
    lines.append("/// Framework permissions: name, protection level as declared, and the label users see.\n")
    lines.append("/// Sorted by name.\n")
    lines.append("pub(crate) const FRAMEWORK_PERMISSIONS: &[(&str, &str, Option<&str>)] = &[\n")
    for name, level, label in permissions:
        label_literal = f"Some({rust_string(label)})" if label else "None"
        lines.append(f"    ({rust_string(name)}, {rust_string(level)}, {label_literal}),\n")
    lines.append("];\n")
    path.write_text("".join(lines))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--public-xml", type=Path, required=True)
    parser.add_argument("--framework-manifest", type=Path, required=True)
    parser.add_argument("--framework-strings", type=Path, required=True)
    parser.add_argument("--sdk-source", required=True, help="for example 'Android SDK Platform 37'")
    parser.add_argument("--manifest-source", required=True, help="AOSP branch, for example android16-qpr2-release")
    parser.add_argument("--out", type=Path, default=Path("src/android/generated"))
    arguments = parser.parse_args()

    attributes = framework_attributes(arguments.public_xml)
    known = dict((name, resource_id) for resource_id, name in attributes)
    # Spot checks against values fixed since early Android releases.
    assert known["label"] == 0x01010001, "public.xml layout changed"
    assert known["minSdkVersion"] == 0x0101020C, "public.xml layout changed"
    assert known["networkSecurityConfig"] == 0x01010527, "public.xml layout changed"

    permissions = framework_permissions(arguments.framework_manifest, framework_strings(arguments.framework_strings))
    assert any(name == "android.permission.CAMERA" and level.startswith("dangerous") for name, level, _ in permissions)

    arguments.out.mkdir(parents=True, exist_ok=True)
    write_attributes(arguments.out / "attributes.rs", attributes, f"{arguments.sdk_source}, public-final.xml")
    write_permissions(
        arguments.out / "permissions.rs",
        permissions,
        f"AOSP frameworks/base core/res ({arguments.manifest_source})",
    )
    print(f"{len(attributes)} attributes, {len(permissions)} permissions")


if __name__ == "__main__":
    main()
