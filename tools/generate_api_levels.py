#!/usr/bin/env python3
"""Generate msec's table of framework APIs Android deprecated or removed.

Input (Apache-2.0, from the Android SDK, generated from AOSP):

  --api-versions   platforms/android-<N>/data/api-versions.xml
                   (every public framework class, method and field with the API levels that
                   added, deprecated and removed it; the data Android lint uses)

Output:

  src/android/generated/api_levels.rs

    FRAMEWORK_API_CHANGES: (signature, deprecated in, removed in) for every class, method and
      field with either level (0 when not), sorted by signature. Signatures use DEX notation:
        class   Landroid/os/AsyncTask;
        method  Landroid/view/Window;->setStatusBarColor(I)V
        field   Landroid/view/WindowManager$LayoutParams;->LAYOUT_IN_DISPLAY_CUTOUT_MODE_DEFAULT
      (fields by name only: a DEX field reference adds the type, which a class's field names
      already make unique).
    FRAMEWORK_SUPERCLASSES: (class, superclass) for every framework class, sorted, so a member
      reached through a subclass resolves to the class that declares it.

Run from the repository root:

  python3 tools/generate_api_levels.py \\
      --api-versions ~/Library/Android/sdk/platforms/android-37.0/data/api-versions.xml \\
      --sdk-source "Android SDK Platform 37"
"""

from __future__ import annotations

import argparse
import xml.etree.ElementTree as ElementTree
from pathlib import Path

HEADER = "// Generated by tools/generate_api_levels.py from {source}. Do not edit by hand.\n\n"


def level(element: ElementTree.Element, attribute: str) -> int:
    value = element.get(attribute)
    return int(value) if value and value.isdigit() else 0


def read(api_versions: Path) -> tuple[list[tuple[str, int, int]], list[tuple[str, str]]]:
    changes: list[tuple[str, int, int]] = []
    superclasses: list[tuple[str, str]] = []
    root = ElementTree.parse(api_versions).getroot()
    for element in root.iter("class"):
        name = element.get("name")
        descriptor = f"L{name};"
        deprecated, removed = level(element, "deprecated"), level(element, "removed")
        if deprecated or removed:
            changes.append((descriptor, deprecated, removed))
        # The superclass in force today: an <extends> without a removed level.
        for extends in element.findall("extends"):
            if not extends.get("removed"):
                superclasses.append((descriptor, f"L{extends.get('name')};"))
                break
        for member in element:
            if member.tag not in ("method", "field"):
                continue
            deprecated, removed = level(member, "deprecated"), level(member, "removed")
            if not (deprecated or removed):
                continue
            member_name = member.get("name")
            changes.append((f"{descriptor}->{member_name}", deprecated, removed))
    changes.sort()
    superclasses.sort()
    return changes, superclasses


def rust_string(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def write(path: Path, changes, superclasses, source: str) -> None:
    lines = [HEADER.format(source=source)]
    lines.append("/// Framework classes, methods and fields Android deprecated or removed: signature in DEX\n")
    lines.append("/// notation, API level that deprecated it, API level that removed it (0: not). Sorted.\n")
    lines.append("pub(crate) const FRAMEWORK_API_CHANGES: &[(&str, u16, u16)] = &[\n")
    for signature, deprecated, removed in changes:
        lines.append(f"    ({rust_string(signature)}, {deprecated}, {removed}),\n")
    lines.append("];\n\n")
    lines.append("/// Framework classes and their superclass, in DEX notation. Sorted.\n")
    lines.append("pub(crate) const FRAMEWORK_SUPERCLASSES: &[(&str, &str)] = &[\n")
    for name, superclass in superclasses:
        lines.append(f"    ({rust_string(name)}, {rust_string(superclass)}),\n")
    lines.append("];\n")
    path.write_text("".join(lines))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--api-versions", type=Path, required=True)
    parser.add_argument("--sdk-source", required=True, help="for example 'Android SDK Platform 37'")
    parser.add_argument("--out", type=Path, default=Path("src/android/generated"))
    arguments = parser.parse_args()
    changes, superclasses = read(arguments.api_versions)
    known = dict((signature, (deprecated, removed)) for signature, deprecated, removed in changes)
    # Spot checks against levels fixed by past releases.
    assert known["Landroid/view/Window;->setStatusBarColor(I)V"] == (35, 0), "api-versions.xml layout changed"
    assert known["Landroid/os/AsyncTask;"][0] == 30, "api-versions.xml layout changed"
    assert ("Landroid/app/Activity;", "Landroid/view/ContextThemeWrapper;") in superclasses
    arguments.out.mkdir(parents=True, exist_ok=True)
    write(arguments.out / "api_levels.rs", changes, superclasses, f"{arguments.sdk_source}, api-versions.xml")
    print(f"{len(changes)} deprecated or removed APIs, {len(superclasses)} superclasses")


if __name__ == "__main__":
    main()
